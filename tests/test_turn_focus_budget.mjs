import assert from 'node:assert/strict';
import {assembleContext,contextConfig,estimatedTokens} from '../federation/context-budget.mjs';
import {attachmentLookup} from '../federation/attachment-autonomy.mjs';
const id='a'.repeat(32), old='b'.repeat(32);
const focus={source_message_id:'current',question:'这里面是什么？',followup:'继续',files:[{id,name:'Flux工作流.json',kind:'document'}]};
const stale='旧文件 Telegram 账号说明。'.repeat(1000);
const memory={goal:stale,summary:{goal:stale},recent:Array.from({length:20},(_,i)=>({id:'old'+i,role:'assistant',content:stale})),turn_focus:focus};
const evidence={wiki:{text:'',reads:[]},templates:{text:'',reads:[]},skills:{text:'',reads:[]}};
const budget={...contextConfig(),input_budget:2400};
const built=assembleContext('回答当前问题','宿主当前请求',evidence,'继续',memory,null,budget);
assert.deepEqual(JSON.parse(built.messages.find(m=>m.content.startsWith('<current_turn_focus>')).content.split('\n')[1]),focus);
assert.equal(built.messages.at(-1).content,'继续');
assert.ok(built.receipt.omitted.length>0);
assert.ok(built.messages.reduce((n,m)=>n+estimatedTokens(m.content)+16,0)<=budget.input_budget);
assert.throws(()=>assembleContext('规则','宿主',evidence,'继续',{...memory,turn_focus:{...focus,question:'重要问题'.repeat(3000)}},null,budget),/完整问题/);
const lookup=attachmentLookup(focus.question,{tools_enabled:true,has_attachments:true,selected_file_ids:[id],files:[{id:old,name:'旧文件.txt',kind:'document'},...focus.files]});
assert.equal(lookup.next({receipts:[],observations:[],allowed:['file_read']}).args.file_id,id);
assert.match(lookup.instruction,/Flux工作流/);
assert.doesNotMatch(lookup.instruction,/旧文件.txt/);
console.log('Turn focus survives history compaction and pins the original attachment.');
