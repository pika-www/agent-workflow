import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../openwiki-upstream/package.json',import.meta.url));
const {JSDOM}=require('jsdom');
const source=fs.readFileSync(new URL('../federation/web/agent-chat.js',import.meta.url),'utf8');
const start=source.indexOf('  function renderReplyTiming(');
const fn=source.slice(start,source.indexOf('\n  }',start)+4);
const dom=new JSDOM('<body/>',{runScripts:'outside-only'});
vm.runInContext(`const make=(tag,cls,text)=>{const e=document.createElement(tag);e.className=cls;e.textContent=text;return e;};${fn};window.render=renderReplyTiming;`,dom.getInternalVMContext());
const render=dom.window.render;
const base={role:'assistant',status:'completed',timing:{request_first_text_ms:1234,request_to_answer_ms:3000,response_completed_ms:3120,first_text_ms:12}};
assert.equal(render(base).textContent,'首字 1.23 秒 · 总用时 3.12 秒');
assert.match(render(base).title,/包含排队和模型等待/);
for(const status of ['streaming','running','failed','queued'])assert.equal(render({...base,status}),null);
assert.equal(render({...base,role:'user'}),null);
assert.equal(render({...base,timing:undefined}),null);
assert.equal(render({...base,timing:{request_to_answer_ms:3000}}).textContent,'首字 未记录 · 总用时 3.00 秒');
assert.equal(render({...base,timing:{request_first_text_ms:0,response_completed_ms:0}}).textContent,'首字 0.00 秒 · 总用时 0.00 秒');
assert.equal(render({...base,timing:{request_first_text_ms:-10,response_completed_ms:Infinity,request_to_answer_ms:'<img>'}}).textContent,'首字 未记录 · 总用时 未记录');
assert.equal(render({...base,timing:{first_text_ms:20,model_ms:200}}).textContent,'首字 未记录 · 总用时 未记录','Never present model-only timing as full request timing');
assert.equal(render(base).querySelector('img'),null);
console.log('Completed-reply timing: full request clock, streaming/failed isolation, missing/invalid values and literal rendering passed.');
