/** Real upstream SDK talks only to a controlled loopback HTTP fixture. */
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {createModel} from '../openwiki-upstream/dist/agent/index.js';
import {reportRuntime} from '../federation/report-model.mjs';
import {runProductAnalysis} from '../federation/product-analysis-turn.mjs';

const requests=[], key='MOCK_REPORT_TRANSPORT_KEY';
const source={url:'https://product.example.test',excerpt:'The public catalog lists applications.',sha256:'a'.repeat(64),title:'Catalog'};
const server=createServer(async(req,res)=>{
  let raw='';for await(const chunk of req)raw+=chunk;
  const body=JSON.parse(raw);
  requests.push({url:req.url,authorization:req.headers.authorization,body});
  const content=(body.max_tokens || body.max_completion_tokens)===1800
    ? JSON.stringify({checks:JSON.parse(body.messages[1].content).assertions.map(a=>({id:a.id,status:'insufficient',reason:'这是受控生成说明，并非网站事实',references:[]}))})
    : (body.max_tokens || body.max_completion_tokens)===2400
    ? JSON.stringify([{url:source.url,quote:'catalog lists applications',fact:'catalog lists applications'}])
    : '# Controlled report\n\nThis report is generated by the HTTP fixture, not a real strong model.\n\nhttps://product.example.test';
  res.writeHead(200,{'content-type':'text/event-stream','cache-control':'no-cache'});
  res.write('data: '+JSON.stringify({id:'fixture',object:'chat.completion.chunk',created:1,model:body.model,choices:[{index:0,delta:{role:'assistant',content},finish_reason:null}]})+'\n\n');
  res.end('data: '+JSON.stringify({id:'fixture',object:'chat.completion.chunk',created:1,model:body.model,choices:[{index:0,delta:{},finish_reason:'stop'}]})+'\n\ndata: [DONE]\n\n');
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const root=await mkdtemp(path.join(tmpdir(),'report-transport-'));
try {
  const file=path.join(root,'report-model.json');
  const base='http://127.0.0.1:'+server.address().port+'/v1';
  await writeFile(file,JSON.stringify({provider:'openai-compatible',model:'fixture-report-model',base_url:base,api_key:key,responses_api:false}),{mode:0o600});
  const route=await reportRuntime({createModel},file);
  const deltas=[];
  const result=await runProductAnalysis(route.runtime,route.provider,route.modelId,0,'Analyze the product',{sources:[source]},{onDelta:text=>deltas.push(text)});
  assert.equal(requests.length,6);
  assert.ok(requests.every(req=>req.url==='/v1/chat/completions'&&req.body.model==='fixture-report-model'&&req.authorization==='Bearer '+key));
  assert.ok(requests.every(req=>req.body.stream===true&&!JSON.stringify(req.body).includes(key)));
  assert.equal(result.model,'fixture-report-model');
  assert.ok(deltas.join('').includes('HTTP fixture'));
  assert.equal(result.analysis_run.assertion_check.status,'corrected_with_limits');
  assert.ok(!result.answer.includes('This report is generated'));
  assert.equal(requests.at(-1).body.response_format.type,'json_schema');
  assert.ok(!JSON.stringify(result).includes(key));
  console.log('Report route actual SDK transport: 6 HTTP fixture calls, correct model/auth, final text streamed, no secret in prompts or receipts.');
} finally {
  server.closeAllConnections();
  await new Promise(resolve=>server.close(resolve));
  await rm(root,{recursive:true,force:true});
}
